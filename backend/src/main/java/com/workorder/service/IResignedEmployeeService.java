package com.workorder.service;


import java.util.Map;


import com.workorder.common.result.Result;
import com.workorder.entity.ResignedEmployee;

/**
 * 离职员工服务接口 — 提供离职员工的查询、导出等业务能力
 */
public interface IResignedEmployeeService {
































  /**

















   * 员工离职处理

















   *

















   * @param userId 员工ID

















   * @param resignType 离职类型（1-主动辞职 2-被动辞退 3-合同到期 4-退休 5-其他）

















   * @param resignReason 离职原因

















   * @param remark 备注

















   * @param operatorId 操作人ID

















   */

















  Result<ResignedEmployee> processResignation(

















      Long userId, Integer resignType, String resignReason, String remark, Long operatorId);



































  /** 获取离职员工列表（分页） */

















  Result<Map<String, Object>> getResignedList(

















      Integer pageNum, Integer pageSize, String keyword, Integer departmentId, Integer resignType);



































  /** 获取离职员工详情 */

















  Result<ResignedEmployee> getResignedById(Long id);



































  /** 获取离职类型列表（用于下拉框） */

















  Result<java.util.List<Map<String, Object>>> getResignTypes();

















}

















